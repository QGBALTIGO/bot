const patterns: Array<[RegExp, string]> = [
  [/\bOperator\b/g, 'Usuário'],
  [/\bOPERATOR\b/g, 'USUÁRIO'],
  [/\bMarket\b/g, 'Loja'],
  [/\bArchive\b/g, 'Coleção'],
  [/\bDashboard\b/g, 'Painel'],
  [/\bHatchery\b/g, 'Incubadora'],
  [/\bMilestones\b/g, 'Conquistas'],
  [/\bCompanions\b/g, 'Companheiros'],
];

function translate(value: string): string {
  let out = EXACT[value] ?? value;
  for (const [from, to] of Object.entries(EXACT).sort((a, b) => b[0].length - a[0].length)) {
    if (out.includes(from)) out = out.split(from).join(to);
  }
  for (const [pattern, replacement] of patterns) out = out.replace(pattern, replacement);
  return out;
}

function translateElement(root: ParentNode) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node: Node | null;
  while ((node = walker.nextNode())) {
    const text = node.nodeValue;
    if (!text || !text.trim()) continue;
    const translated = translate(text);
    if (translated !== text) node.nodeValue = translated;
  }

  if (root instanceof Element) {
    for (const attr of ['aria-label', 'title', 'placeholder']) {
      const current = root.getAttribute(attr);
      if (current) root.setAttribute(attr, translate(current));
    }
  }
  root.querySelectorAll?.('[aria-label], [title], [placeholder]').forEach((element) => {
    for (const attr of ['aria-label', 'title', 'placeholder']) {
      const current = element.getAttribute(attr);
      if (current) element.setAttribute(attr, translate(current));
    }
  });
}

export function installPtBR() {
  document.documentElement.lang = 'pt-BR';
  document.title = 'AniNexus';
  const run = () => translateElement(document.body);
  if (document.body) run();
  else document.addEventListener('DOMContentLoaded', run, { once: true });

  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      for (const node of Array.from(mutation.addedNodes)) {
        if (node instanceof Element) translateElement(node);
        else if (node.nodeType === Node.TEXT_NODE && node.nodeValue) {
          node.nodeValue = translate(node.nodeValue);
        }
      }
    }
  });
  const start = () => observer.observe(document.body, { childList: true, subtree: true });
  if (document.body) start();
  else document.addEventListener('DOMContentLoaded', start, { once: true });
}
